"""Generate the project's original outline icon atlas. Requires Pillow."""
from PIL import Image, ImageDraw
from pathlib import Path
SIZE=24; S=4
names=['home','code','tool','sliders','pulse','file','hand','layers','target','reset','wifi','gear','gauge','spindle','wave','thermo','bolt','check','alert','insert']
out=Path(__file__).resolve().parents[1]/'firmware/esp32-hmi/assets'
images=[]
for name in names:
 im=Image.new('RGBA',(SIZE*S,SIZE*S));d=ImageDraw.Draw(im);c=(199,225,249,255);width=round(1.7*S)
 def line(p,fill=c,w=width):d.line([(x*S,y*S) for x,y in p],fill=fill,width=w,joint='curve')
 def ellipse(box,fill=None,outline=c,w=width):d.ellipse(tuple(round(v*S) for v in box),fill=fill,outline=outline,width=w)
 def rect(box,fill=None,outline=c,w=width):d.rectangle(tuple(round(v*S) for v in box),fill=fill,outline=outline,width=w)
 if name=='home':line([(2,11),(12,2),(22,11)]);line([(5,9),(5,22),(10,22),(10,15),(15,15),(15,22),(20,22),(20,9)])
 elif name=='code':line([(7,5),(2,12),(7,19)]);line([(17,5),(22,12),(17,19)]);line([(14,3),(10,21)])
 elif name=='tool':line([(3,20),(13,8),(17,12),(6,23),(3,20)]);line([(13,4),(17,0),(24,7),(20,11),(13,4)])
 elif name=='sliders':
  for y,x in [(5,8),(12,16),(19,10)]:line([(2,y),(22,y)]);ellipse((x-2,y-2,x+2,y+2),fill=(10,18,25,255))
 elif name=='pulse':line([(1,13),(6,13),(9,3),(14,22),(18,9),(21,13),(24,13)])
 elif name=='file':line([(5,1),(15,1),(21,7),(21,23),(5,23),(5,1)]);line([(15,1),(15,7),(21,7)]);line([(8,12),(17,12)]);line([(8,16),(17,16)]);line([(8,20),(15,20)])
 elif name=='hand':line([(8,13),(8,3),(10,1),(12,3),(12,10),(14,5),(16,6),(16,11),(18,7),(20,8),(20,16),(17,22),(9,22),(2,14),(3,11),(8,15)])
 elif name=='layers':
  for y in [0,7,14]:line([(2,6+y),(12,1+y),(22,6+y),(12,11+y),(2,6+y)])
 elif name in ['target','gear']:
  ellipse((4,4,20,20));ellipse((9,9,15,15));
  for p in [[(12,0),(12,7)],[(12,17),(12,24)],[(0,12),(7,12)],[(17,12),(24,12)]]:line(p)
 elif name=='reset':
  d.arc((3*S,3*S,21*S,21*S),35,325,fill=c,width=width);line([(21,2),(21,9),(15,7)])
 elif name=='wifi':
  for b in [(1,3,23,23),(5,8,19,22),(9,13,15,21)]:d.arc(tuple(v*S for v in b),210,330,fill=c,width=width)
  ellipse((11,20,13,22),fill=c)
 elif name=='gauge':
  d.arc((2*S,2*S,22*S,22*S),135,405,fill=c,width=width);line([(12,12),(18,6)]);ellipse((10,10,14,14),fill=c)
 elif name=='spindle':rect((6,3,18,18));ellipse((8,6,16,14));line([(12,0),(12,4)]);line([(3,20),(21,20)]);ellipse((3,18,7,22));ellipse((17,18,21,22))
 elif name=='wave':line([(1,8),(5,4),(9,4),(15,12),(19,12),(23,8)]);line([(1,17),(5,13),(9,13),(15,21),(19,21),(23,17)])
 elif name=='thermo':line([(9,16),(9,4),(12,1),(15,4),(15,16)]);ellipse((7,13,17,23));line([(12,7),(12,19)])
 elif name=='bolt':line([(14,1),(5,14),(11,14),(9,23),(20,9),(13,9),(14,1)])
 elif name=='check':ellipse((1,1,23,23),fill=(36,170,29,255),outline=(103,235,60,255));line([(6,12),(10,17),(18,7)],fill=(255,255,255,255))
 elif name=='alert':line([(12,1),(24,22),(1,22),(12,1)],fill=(255,255,255,255));line([(12,7),(12,15)],fill=(255,255,255,255));ellipse((11,18,13,20),fill=(255,255,255,255))
 elif name=='insert':
  d.polygon([(4*S,4*S),(23*S,4*S),(19*S,21*S),(1*S,21*S)],fill=(246,190,48,255),outline=(255,222,99,255),width=S);ellipse((9,9,16,16),fill=(48,40,27,255),outline=(255,224,101,255))
 images.append(im.resize((SIZE,SIZE),Image.Resampling.LANCZOS))
with (out/'tv4_icons.c').open('w') as f:
 f.write('/* Original procedural outline icons; generated by tools/generate_icons.py. */\n#include "lvgl.h"\n')
 for name,im in zip(names,images):
  data=[]
  for red,g,b,a in im.getdata():data.extend([b,g,red,a])
  f.write('static const uint8_t '+name+'_pixels[] = {\n')
  for i in range(0,len(data),32):f.write(','.join(map(str,data[i:i+32]))+',\n')
  f.write('};\nconst lv_image_dsc_t tv4_icon_'+name+'={.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_ARGB8888,.w=24,.h=24,.stride=96},.data_size=sizeof('+name+'_pixels),.data='+name+'_pixels};\n')
